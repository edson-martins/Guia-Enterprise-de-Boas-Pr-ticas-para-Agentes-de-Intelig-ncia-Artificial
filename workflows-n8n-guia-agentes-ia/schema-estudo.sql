-- ============================================================
-- Guia Enterprise de Boas Práticas para Agentes de IA
-- Schema de ESTUDO — banco isolado, só para os workflows do livro
-- ============================================================
--
-- Este schema é INDEPENDENTE de qualquer sistema de produção.
-- Use um banco (ou pelo menos um schema) dedicado só pra este ambiente
-- de estudo — nunca aponte estes workflows para um banco que já
-- roda um sistema real.
--
-- Sugestão: crie um database separado antes de rodar este script:
--   CREATE DATABASE guia_agentes_estudo;
-- e conecte nele antes de continuar.

-- ============================================================
-- 1. business — cadastro simplificado (schema achatado de propósito,
--    diferente de um sistema real com múltiplas tabelas normalizadas,
--    pra manter o foco didático nos workflows, não no modelo de dados)
-- ============================================================
CREATE TABLE IF NOT EXISTS business (
  business_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                  TEXT NOT NULL,
  waha_session          TEXT NOT NULL UNIQUE,
  instrucoes            TEXT NOT NULL DEFAULT '',
  endereco              TEXT,
  horario_funcionamento TEXT,
  telefone_contato      TEXT,
  active                BOOLEAN NOT NULL DEFAULT true,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 2. faq — usada pelo workflow 03 (faq-dinamico-sheets.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS faq (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id    BIGINT NOT NULL REFERENCES business(business_id),
  pergunta       TEXT NOT NULL,
  resposta       TEXT NOT NULL,
  categoria      TEXT,
  atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (business_id, pergunta)
);

-- ============================================================
-- 3. execution_logs — usada pelos workflows 04 e 06
-- ============================================================
CREATE TABLE IF NOT EXISTS execution_logs (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_name  TEXT NOT NULL,
  event_type     TEXT NOT NULL,
  level          TEXT NOT NULL DEFAULT 'info',
  message        TEXT,
  chat_id        TEXT,
  business_id    BIGINT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 4. conversation_messages — usada pelo workflow 07 (avaliacao-pipeline.json)
--    Nota: se você também importar os workflows 01/02/04/05 e usar o node
--    de Memória (memoryPostgresChat), ele cria sua PRÓPRIA tabela de
--    histórico automaticamente (nome pode variar por versão do n8n).
--    Esta tabela aqui é a versão simplificada, própria do livro, pra
--    você conseguir rodar o pipeline de avaliação de forma independente,
--    sem depender de já ter conversas reais acumuladas.
-- ============================================================
CREATE TABLE IF NOT EXISTS conversation_messages (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id  BIGINT NOT NULL REFERENCES business(business_id),
  chat_id      TEXT NOT NULL,
  role         TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content      TEXT NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 5. conversation_evals — usada pelo workflow 07
-- ============================================================
CREATE TABLE IF NOT EXISTS conversation_evals (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id                 TEXT NOT NULL,
  business_id             BIGINT,
  resolucao               INT,
  tom                     INT,
  precisao                INT,
  escalacao_apropriada    INT,
  nota_geral              INT,
  justificativa           TEXT,
  avaliado_em             TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 6. appointments — usada pelo workflow 08 (lembrete-agendamento.json)
--    e pelo sub-agente de agendamento (via API de estudo)
-- ============================================================
CREATE TABLE IF NOT EXISTS appointments (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id         BIGINT NOT NULL REFERENCES business(business_id),
  chat_id             TEXT NOT NULL,
  patient_name        TEXT NOT NULL,
  specialty           TEXT,
  appointment_at      TIMESTAMPTZ NOT NULL,
  status              TEXT NOT NULL DEFAULT 'agendado',
  calendar_event_id   TEXT,
  reminder_sent_at    TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 7. document_extractions — usada pelo workflow 10 (documento-analise.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS document_extractions (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arquivo_url      TEXT NOT NULL,
  dados_extraidos  JSONB NOT NULL,
  status           TEXT NOT NULL,
  criado_em        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 8. leads — usada pelo workflow 02 (qualificacao-leads.json),
--    via a API de estudo (ambiente-estudo-api.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS leads (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id      TEXT NOT NULL,
  nome         TEXT,
  empresa      TEXT,
  cargo        TEXT,
  necessidade  TEXT,
  prazo        TEXT,
  criado_em    TIMESTAMPTZ NOT NULL DEFAULT now()
);

