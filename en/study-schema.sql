-- ============================================================
-- Enterprise Guide to Best Practices for AI Agents
-- STUDY schema: an isolated database, only for the book's workflows
-- ============================================================
--
-- This schema is INDEPENDENT of any production system.
-- Use a database (or at least a schema) dedicated to this study
-- environment. Never point these workflows at a database that
-- already runs a real system.
--
-- Suggestion: create a separate database before running this script:
--   CREATE DATABASE ai_agents_guide_study;
-- and connect to it before continuing.

-- ============================================================
-- 1. business: a simplified registry (deliberately flattened schema,
--    unlike a real system with several normalized tables, to keep
--    the teaching focus on the workflows, not on the data model)
-- ============================================================
CREATE TABLE IF NOT EXISTS business (
  business_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  waha_session    TEXT NOT NULL UNIQUE,
  instructions    TEXT NOT NULL DEFAULT '',
  address         TEXT,
  opening_hours   TEXT,
  contact_phone   TEXT,
  active          BOOLEAN NOT NULL DEFAULT true,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 2. faq: used by workflow 03 (dynamic-faq-sheets.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS faq (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id  BIGINT NOT NULL REFERENCES business(business_id),
  question     TEXT NOT NULL,
  answer       TEXT NOT NULL,
  category     TEXT,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (business_id, question)
);

-- ============================================================
-- 3. execution_logs: used by workflows 04 and 06
-- ============================================================
CREATE TABLE IF NOT EXISTS execution_logs (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_name  TEXT NOT NULL,
  event_type     TEXT NOT NULL,
  level          TEXT NOT NULL DEFAULT 'info',
  message        TEXT,
  chat_id        TEXT,
  business_id    BIGINT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 4. conversation_messages: used by workflow 07 (evaluation-pipeline.json)
--    Note: if you also import workflows 01/02/04/05 and use the
--    Memory node (memoryPostgresChat), it creates its OWN history
--    table automatically (the name may vary by n8n version).
--    This table is the book's own simplified version, so that you
--    can run the evaluation pipeline on its own, without needing
--    real conversations to have built up first.
-- ============================================================
CREATE TABLE IF NOT EXISTS conversation_messages (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id  BIGINT NOT NULL REFERENCES business(business_id),
  chat_id      TEXT NOT NULL,
  role         TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content      TEXT NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 5. conversation_evals: used by workflow 07
-- ============================================================
CREATE TABLE IF NOT EXISTS conversation_evals (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id                 TEXT NOT NULL,
  business_id             BIGINT,
  resolution              INT,
  tone                    INT,
  accuracy                INT,
  appropriate_escalation  INT,
  overall_score           INT,
  justification           TEXT,
  evaluated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 6. appointments: used by workflow 08 (appointment-reminder.json)
--    and by the scheduling sub-agent (through the study API)
-- ============================================================
CREATE TABLE IF NOT EXISTS appointments (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id         BIGINT NOT NULL REFERENCES business(business_id),
  chat_id             TEXT NOT NULL,
  patient_name        TEXT NOT NULL,
  specialty           TEXT,
  appointment_at      TIMESTAMPTZ NOT NULL,
  status              TEXT NOT NULL DEFAULT 'scheduled',
  calendar_event_id   TEXT,
  reminder_sent_at    TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 7. document_extractions: used by workflow 10 (document-analysis.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS document_extractions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_url        TEXT NOT NULL,
  extracted_data  JSONB NOT NULL,
  status          TEXT NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 8. leads: used by workflow 02 (lead-qualification.json),
--    through the study API (study-environment-api.json)
-- ============================================================
CREATE TABLE IF NOT EXISTS leads (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id     TEXT NOT NULL,
  name        TEXT,
  company     TEXT,
  job_title   TEXT,
  need        TEXT,
  deadline    TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

